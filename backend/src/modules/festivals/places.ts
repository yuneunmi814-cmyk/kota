const SUFFIX = ['특별자치시', '특별자치도', '광역시', '특별시', '시', '군', '구']

/** '강릉시' → { stem: '강릉', kind: '시' } · 접미사가 없으면 kind는 '' */
export function splitSigungu(name: string): { stem: string; kind: string } {
  const n = name.trim()
  for (const s of SUFFIX) {
    if (n.length > s.length && n.endsWith(s)) return { stem: n.slice(0, -s.length), kind: s }
  }
  return { stem: n, kind: '' }
}

/**
 * 시군구명을 3개 언어로. 사전에 없어도 음역으로 항상 결과를 낸다(신설·통합 구 대응).
 * 구는 영문에 '-gu'를 붙여 현지에서 통하게 한다(Jung-gu) — 시·군은 접미사를 뺀다.
 */
export function translateSigungu(name: string): Place {
  // '대구'처럼 이름 자체가 사전 표제어면 접미사를 떼지 않는다 (안 그러면 '대'+'구' → Dae-gu)
  const whole = ALL_JA[name.trim()]
  if (whole) {
    const s = name.trim()
    return { en: romanize(s), ja: whole, th: SIGUNGU_TH_OVERRIDE[s] ?? thai(s) }
  }
  const { stem, kind } = splitSigungu(name)
  const isGu = kind === '구'
  const ja = ALL_JA[stem] ?? stem
  const th = SIGUNGU_TH_OVERRIDE[stem] ?? thai(stem)
  return {
    en: isGu ? `${romanize(stem)}-gu` : romanize(stem),
    ja: `${ja}${isGu ? '区' : kind === '군' ? '郡' : kind === '시' ? '市' : ''}`,
    th: isGu ? `${th}กู` : th,
  }
}

/** 시도명을 3개 언어로. 사전에 없으면 음역 */
export function translateSido(name: string): Place {
  const hit = SIDO[name.trim()]
  if (hit) return hit
  const { stem } = splitSigungu(name)
  return { en: romanize(stem), ja: SIGUNGU_JA[stem] ?? stem, th: thai(stem) }
}

/**
 * 외국인이 읽을 지명 문자열 — 주소 전체가 아니라 '어디쯤인지'만.
 * en 'Gangneung, Gangwon-do' · ja '江原道 江陵市' · th 'คังนึง คังวอน'
 */
export function placeName(sido: string | null, sigungu: string | null, lang: 'en' | 'ja' | 'th'): string | null {
  if (!sido && !sigungu) return null
  // '동구, 중구'처럼 복수 표기가 들어오면 첫 번째만 쓴다
  const one = sigungu?.split(',')[0]?.trim() || null
  const si = sido ? translateSido(sido)[lang] : null
  const gu = one ? translateSigungu(one)[lang] : null
  if (!gu) return si
  if (!si) return gu
  // 일본어·태국어는 넓은 곳 → 좁은 곳, 영어는 반대
  return lang === 'en' ? `${gu}, ${si}` : `${si} ${gu}`
}

